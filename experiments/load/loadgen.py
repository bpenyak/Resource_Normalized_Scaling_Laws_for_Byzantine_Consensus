#!/usr/bin/env python3
"""Load generator with per-sender nonce ownership.

Each of the ``c`` senders owns a distinct externally-owned account and its own
nonce counter, so submission is embarrassingly parallel. A shared nonce counter
serializes signing and submission and caps measured throughput far below the
consensus limit -- that is the bottleneck we are explicitly avoiding here.

Throughput is measured from *on-chain block contents*, not from client
acknowledgements, so failed submissions cannot inflate the result.

SECURITY: the private keys consumed by this script come from
``network/accounts.json`` and are deterministic development keys generated by
``docker/gen_network.py`` from a public seed. They fund nothing of value.
"""

from __future__ import annotations

import argparse
import json
import queue
import statistics
import threading
import time
from pathlib import Path

import requests
from eth_account import Account


class Sender(threading.Thread):
    """One signing thread with an exclusive nonce range."""

    def __init__(self, rpc_url: str, priv_key: str, chain_id: int,
                 target: str, gas_price: int, stop_evt: threading.Event,
                 errors: queue.Queue):
        super().__init__(daemon=True)
        self.rpc_url = rpc_url
        self.account = Account.from_key(priv_key)
        self.chain_id = chain_id
        self.target = target
        self.gas_price = gas_price
        self.stop_evt = stop_evt
        self.errors = errors
        self.sent = 0
        self.session = requests.Session()
        self._id = 0

    def _rpc(self, method: str, params: list):
        self._id += 1
        r = self.session.post(self.rpc_url, json={
            "jsonrpc": "2.0", "id": self._id,
            "method": method, "params": params}, timeout=15)
        r.raise_for_status()
        body = r.json()
        if "error" in body:
            raise RuntimeError(body["error"])
        return body["result"]

    def run(self) -> None:
        try:
            nonce = int(self._rpc("eth_getTransactionCount",
                                  [self.account.address, "pending"]), 16)
        except Exception as exc:  # noqa: BLE001
            self.errors.put(f"{self.account.address}: nonce init: {exc}")
            return

        while not self.stop_evt.is_set():
            tx = {
                "to": self.target,
                "value": 1,
                "gas": 21000,
                "gasPrice": self.gas_price,
                "nonce": nonce,
                "chainId": self.chain_id,
            }
            try:
                signed = self.account.sign_transaction(tx)
                raw = getattr(signed, "raw_transaction", None)
                if raw is None:  # eth-account < 0.13
                    raw = signed.rawTransaction
                self._rpc("eth_sendRawTransaction", ["0x" + bytes(raw).hex()])
                nonce += 1
                self.sent += 1
            except Exception as exc:  # noqa: BLE001
                # A full transaction pool is expected under saturation; back off
                # instead of aborting the run.
                self.errors.put(str(exc))
                time.sleep(0.05)
                try:
                    nonce = int(self._rpc("eth_getTransactionCount",
                                          [self.account.address, "pending"]), 16)
                except Exception:  # noqa: BLE001
                    pass


def rpc_call(url: str, method: str, params: list, rid: int = 1):
    r = requests.post(url, json={"jsonrpc": "2.0", "id": rid,
                                 "method": method, "params": params}, timeout=15)
    r.raise_for_status()
    body = r.json()
    if "error" in body:
        raise RuntimeError(body["error"])
    return body["result"]


def block_number(url: str) -> int:
    return int(rpc_call(url, "eth_blockNumber", []), 16)


def sample_blocks(url: str, lo: int, hi: int) -> list[dict]:
    out = []
    for h in range(lo, hi + 1):
        blk = rpc_call(url, "eth_getBlockByNumber", [hex(h), False])
        if blk is None:
            continue
        out.append({
            "number": int(blk["number"], 16),
            "timestamp": int(blk["timestamp"], 16),
            "tx_count": len(blk["transactions"]),
            "gas_used": int(blk["gasUsed"], 16),
            "miner": blk.get("miner"),
        })
    return out


def measure(url: str, warmup: int, duration: int, drain: int) -> dict:
    """Wait out the warm-up, then measure a steady-state interval on chain."""
    time.sleep(warmup)
    start_block = block_number(url)
    start_wall = time.time()
    time.sleep(duration)
    end_block = block_number(url)
    end_wall = time.time()
    time.sleep(drain)

    blocks = sample_blocks(url, start_block + 1, end_block)
    if len(blocks) < 2:
        raise RuntimeError("fewer than two blocks in the measurement window")

    total_tx = sum(b["tx_count"] for b in blocks)
    span = blocks[-1]["timestamp"] - blocks[0]["timestamp"]
    chain_seconds = span if span > 0 else (end_wall - start_wall)
    intervals = [b2["timestamp"] - b1["timestamp"]
                 for b1, b2 in zip(blocks, blocks[1:])]

    return {
        "start_block": blocks[0]["number"],
        "end_block": blocks[-1]["number"],
        "blocks": len(blocks),
        "total_tx": total_tx,
        "chain_seconds": chain_seconds,
        "wall_seconds": end_wall - start_wall,
        "tps": total_tx / chain_seconds if chain_seconds else 0.0,
        "block_interval_mean": statistics.fmean(intervals) if intervals else None,
        "block_interval_stdev": (statistics.pstdev(intervals)
                                 if len(intervals) > 1 else 0.0),
        "tx_per_block_mean": total_tx / len(blocks),
        "block_detail": blocks,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rpc", required=True, help="JSON-RPC endpoint of validator0")
    ap.add_argument("--accounts", type=Path, required=True,
                    help="network/accounts.json produced by gen_network.py")
    ap.add_argument("--concurrency", type=int, required=True,
                    help="number of independent senders (c)")
    ap.add_argument("--chain-id", type=int, default=1337)
    ap.add_argument("--gas-price", type=int, default=0)
    ap.add_argument("--warmup", type=int, default=60)
    ap.add_argument("--duration", type=int, default=300)
    ap.add_argument("--drain", type=int, default=30)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    accounts = json.loads(args.accounts.read_text(encoding="utf-8"))
    if args.concurrency > len(accounts):
        raise SystemExit(f"need {args.concurrency} funded accounts, "
                         f"have {len(accounts)}")

    target = accounts[-1]["address"]
    stop_evt = threading.Event()
    errors: queue.Queue = queue.Queue()

    senders = [Sender(args.rpc, accounts[i]["private_key"], args.chain_id,
                      target, args.gas_price, stop_evt, errors)
               for i in range(args.concurrency)]
    for s in senders:
        s.start()

    try:
        result = measure(args.rpc, args.warmup, args.duration, args.drain)
    finally:
        stop_evt.set()
        for s in senders:
            s.join(timeout=10)

    err_list = []
    while not errors.empty() and len(err_list) < 50:
        err_list.append(errors.get())

    result.update({
        "concurrency": args.concurrency,
        "submitted": sum(s.sent for s in senders),
        "submit_errors_sampled": err_list,
    })

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(f"tps={result['tps']:.2f} blocks={result['blocks']} "
          f"tx={result['total_tx']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
